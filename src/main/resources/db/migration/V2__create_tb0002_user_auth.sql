ALTER TABLE TB0001_PERSON
ADD COLUMN C0001_CREATED_BY UUID,
ADD COLUMN C0001_UPDATED_BY UUID;

ALTER TABLE TB0001_PERSON
ADD CONSTRAINT fk_person_created_by FOREIGN KEY (C0001_CREATED_BY)
    REFERENCES TB0002_USER_AUTH(C0002_USER_ID),
ADD CONSTRAINT fk_person_updated_by FOREIGN KEY (C0001_UPDATED_BY)
    REFERENCES TB0002_USER_AUTH(C0002_USER_ID);

CREATE INDEX IX0001_CREATED_BY ON TB0001_PERSON(C0001_CREATED_BY);
CREATE INDEX IX0001_UPDATED_BY ON TB0001_PERSON(C0001_UPDATED_BY);

COMMENT ON COLUMN TB0001_PERSON.C0001_CREATED_BY IS 'UserAuth que criou o registro (pode ser NULL na criação inicial)';
COMMENT ON COLUMN TB0001_PERSON.C0001_UPDATED_BY IS 'UserAuth que atualizou o registro pela última vez';
