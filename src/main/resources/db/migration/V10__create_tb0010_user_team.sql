-- Criar Sequence
CREATE SEQUENCE seq_tb0010_user_team START 1;

-- Criar Tabela
CREATE TABLE TB0010_USER_TEAM (
    C0010_ID UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    C0010_USER_ID UUID NOT NULL,
    C0010_TEAM_ID UUID NOT NULL,
    C0010_ROLE VARCHAR(50) DEFAULT 'MEMBER' NOT NULL,
    C0010_APPROVED BOOLEAN DEFAULT FALSE NOT NULL,
    C0010_ACTIVE BOOLEAN DEFAULT TRUE NOT NULL,
    C0010_CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    C0010_UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    C0010_CREATED_BY UUID NOT NULL,
    C0010_UPDATED_BY UUID NOT NULL,
    C0010_SQ_ID INT NOT NULL DEFAULT nextval('seq_tb0010_user_team'),
    CONSTRAINT chk_user_team_role CHECK (C0010_ROLE IN ('LEAD', 'MEMBER')),
    CONSTRAINT fk_user_team_user FOREIGN KEY (C0010_USER_ID)
        REFERENCES TB0002_USER_AUTH(C0002_USER_ID) ON DELETE CASCADE,
    CONSTRAINT fk_user_team_team FOREIGN KEY (C0010_TEAM_ID)
        REFERENCES TB0006_TEAM(C0006_TEAM_ID) ON DELETE CASCADE,
    CONSTRAINT fk_user_team_created_by FOREIGN KEY (C0010_CREATED_BY)
        REFERENCES TB0002_USER_AUTH(C0002_USER_ID),
    CONSTRAINT fk_user_team_updated_by FOREIGN KEY (C0010_UPDATED_BY)
        REFERENCES TB0002_USER_AUTH(C0002_USER_ID)
);

-- Criar Índices
CREATE UNIQUE INDEX IX0010_SQ_ID ON TB0010_USER_TEAM (C0010_SQ_ID);
CREATE INDEX IX0010_USER_ID ON TB0010_USER_TEAM (C0010_USER_ID);
CREATE INDEX IX0010_TEAM_ID ON TB0010_USER_TEAM (C0010_TEAM_ID);
CREATE INDEX IX0010_ROLE ON TB0010_USER_TEAM (C0010_ROLE);
CREATE INDEX IX0010_APPROVED ON TB0010_USER_TEAM (C0010_APPROVED);
CREATE INDEX IX0010_ACTIVE ON TB0010_USER_TEAM (C0010_ACTIVE) WHERE C0010_ACTIVE = TRUE;
CREATE INDEX IX0010_CREATED_BY ON TB0010_USER_TEAM (C0010_CREATED_BY);
CREATE INDEX IX0010_CREATED_AT ON TB0010_USER_TEAM (C0010_CREATED_AT DESC);

-- Índice único: um usuário não pode ter múltiplos vínculos ativos com o mesmo time
CREATE UNIQUE INDEX IX0010_USER_TEAM_UNIQUE
ON TB0010_USER_TEAM (C0010_USER_ID, C0010_TEAM_ID)
WHERE C0010_ACTIVE = TRUE;

-- Índice para buscar vínculos aprovados
CREATE INDEX IX0010_USER_TEAM_APPROVED
ON TB0010_USER_TEAM (C0010_USER_ID, C0010_TEAM_ID, C0010_APPROVED)
WHERE C0010_ACTIVE = TRUE AND C0010_APPROVED = TRUE;

-- Adicionar Comentários
COMMENT ON TABLE TB0010_USER_TEAM IS 'Tabela de relacionamento entre usuários e times';
COMMENT ON COLUMN TB0010_USER_TEAM.C0010_ID IS 'Identificador único do relacionamento';
COMMENT ON COLUMN TB0010_USER_TEAM.C0010_USER_ID IS 'ID do usuário';
COMMENT ON COLUMN TB0010_USER_TEAM.C0010_TEAM_ID IS 'ID do time';
COMMENT ON COLUMN TB0010_USER_TEAM.C0010_ROLE IS 'Papel do usuário no time (LEAD, MEMBER)';
COMMENT ON COLUMN TB0010_USER_TEAM.C0010_APPROVED IS 'Indica se o vínculo foi aprovado (LEAD auto-aprovado, outros precisam aprovação)';
COMMENT ON COLUMN TB0010_USER_TEAM.C0010_ACTIVE IS 'Indica se o relacionamento está ativo';
COMMENT ON COLUMN TB0010_USER_TEAM.C0010_CREATED_AT IS 'Data e hora de criação do registro';
COMMENT ON COLUMN TB0010_USER_TEAM.C0010_UPDATED_AT IS 'Data e hora da última atualização do registro';
COMMENT ON COLUMN TB0010_USER_TEAM.C0010_CREATED_BY IS 'ID do usuário que criou o registro';
COMMENT ON COLUMN TB0010_USER_TEAM.C0010_UPDATED_BY IS 'ID do usuário que atualizou o registro pela última vez';
COMMENT ON COLUMN TB0010_USER_TEAM.C0010_SQ_ID IS 'ID sequencial numérico';

-- Conceder Permissões
GRANT SELECT, INSERT, UPDATE, DELETE ON TB0010_USER_TEAM TO "TIME-TRACKER-API";
GRANT USAGE, SELECT ON SEQUENCE seq_tb0010_user_team TO "TIME-TRACKER-API";
