CREATE SEQUENCE seq_TB0001_PERSON START 1;

CREATE TABLE TB0001_PERSON (
    C0001_ID UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    C0001_NAME TEXT NOT NULL,
    C0001_EMAIL TEXT NOT NULL,
    C0001_PHONE TEXT,
    C0001_NAME_HASH VARCHAR(64),
    C0001_EMAIL_HASH VARCHAR(64),
    C0001_PHONE_HASH VARCHAR(64),
    C0001_LOCALE VARCHAR(5),
    C0001_AGE INTEGER,
    C0001_CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    C0001_UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    C0001_SQ_ID INT NOT NULL DEFAULT nextval('seq_TB0001_PERSON'),
    C0001_ACTIVE BOOLEAN DEFAULT TRUE NOT NULL
    -- C0001_CREATED_BY e C0001_UPDATED_BY adicionados em V2 (FK circular com TB0002_USER_AUTH)
);

CREATE UNIQUE INDEX IX0001_SQ_ID ON TB0001_PERSON (C0001_SQ_ID);
CREATE INDEX IX0001_ACTIVE ON TB0001_PERSON (C0001_ACTIVE) WHERE C0001_ACTIVE = TRUE;
CREATE INDEX IX0001_CREATED_AT ON TB0001_PERSON (C0001_CREATED_AT DESC);
CREATE UNIQUE INDEX IX0001_EMAIL_HASH ON TB0001_PERSON (C0001_EMAIL_HASH);
CREATE INDEX IX0001_NAME_HASH ON TB0001_PERSON (C0001_NAME_HASH);
CREATE INDEX IX0001_PHONE_HASH ON TB0001_PERSON (C0001_PHONE_HASH);

COMMENT ON TABLE TB0001_PERSON IS 'Tabela de dados pessoais da pessoa';
COMMENT ON COLUMN TB0001_PERSON.C0001_ID IS 'Identificador único da pessoa, compartilhado com TB0002_USER_AUTH se existir';
COMMENT ON COLUMN TB0001_PERSON.C0001_NAME IS 'Nome completo da pessoa (criptografado)';
COMMENT ON COLUMN TB0001_PERSON.C0001_EMAIL IS 'Endereço de email da pessoa (criptografado)';
COMMENT ON COLUMN TB0001_PERSON.C0001_PHONE IS 'Telefone da pessoa (criptografado)';
COMMENT ON COLUMN TB0001_PERSON.C0001_NAME_HASH IS 'Hash do nome para busca exata';
COMMENT ON COLUMN TB0001_PERSON.C0001_EMAIL_HASH IS 'Hash do email para busca exata';
COMMENT ON COLUMN TB0001_PERSON.C0001_PHONE_HASH IS 'Hash do telefone para busca exata';
COMMENT ON COLUMN TB0001_PERSON.C0001_LOCALE IS 'Idioma preferido do usuário';
COMMENT ON COLUMN TB0001_PERSON.C0001_AGE IS 'Idade da pessoa';
COMMENT ON COLUMN TB0001_PERSON.C0001_SQ_ID IS 'ID sequencial numérico';
COMMENT ON COLUMN TB0001_PERSON.C0001_ACTIVE IS 'Indica se os dados da pessoa estão ativos';

GRANT SELECT, INSERT, UPDATE, DELETE ON TB0001_PERSON TO "TIME-TRACKER-API";
