CREATE SEQUENCE seq_TB0013_SYSTEM_CONFIG START 1;

CREATE TABLE TB0013_SYSTEM_CONFIG (
    C0013_ID UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    C0013_CONFIG_KEY VARCHAR(100) NOT NULL,
    C0013_CONFIG_VALUE VARCHAR(500),
    C0013_VALUE_TYPE VARCHAR(50) NOT NULL,
    C0013_DESCRIPTION TEXT,
    C0013_CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    C0013_UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    C0013_SQ_ID INT NOT NULL DEFAULT nextval('seq_TB0013_SYSTEM_CONFIG'),
    C0013_ACTIVE BOOLEAN DEFAULT TRUE NOT NULL
);

CREATE UNIQUE INDEX IX0013_SQ_ID ON TB0013_SYSTEM_CONFIG (C0013_SQ_ID);
CREATE UNIQUE INDEX IX0013_CONFIG_KEY ON TB0013_SYSTEM_CONFIG (C0013_CONFIG_KEY);
CREATE INDEX IX0013_ACTIVE ON TB0013_SYSTEM_CONFIG (C0013_ACTIVE) WHERE C0013_ACTIVE = TRUE;

COMMENT ON TABLE TB0013_SYSTEM_CONFIG IS 'System configuration table';
COMMENT ON COLUMN TB0013_SYSTEM_CONFIG.C0013_ID IS 'Unique identifier of the configuration';
COMMENT ON COLUMN TB0013_SYSTEM_CONFIG.C0013_CONFIG_KEY IS 'Unique configuration key';
COMMENT ON COLUMN TB0013_SYSTEM_CONFIG.C0013_CONFIG_VALUE IS 'Configuration value (up to 500 characters)';
COMMENT ON COLUMN TB0013_SYSTEM_CONFIG.C0013_VALUE_TYPE IS 'Value type: STRING, STRING_LIST, BOOLEAN, INTEGER';
COMMENT ON COLUMN TB0013_SYSTEM_CONFIG.C0013_DESCRIPTION IS 'Description of the configuration purpose';
COMMENT ON COLUMN TB0013_SYSTEM_CONFIG.C0013_SQ_ID IS 'Numeric sequential ID';
COMMENT ON COLUMN TB0013_SYSTEM_CONFIG.C0013_ACTIVE IS 'Indicates whether the configuration is active';

