-- Criar Sequence
CREATE SEQUENCE seq_tb0006_team START 1;

-- Criar Tabela
CREATE TABLE TB0006_TEAM (
    C0006_TEAM_ID UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    C0006_COMPANY_ID UUID NOT NULL,
    C0006_NAME VARCHAR(200) NOT NULL,
    C0006_DESCRIPTION TEXT,
    C0006_ACTIVE BOOLEAN DEFAULT TRUE NOT NULL,
    C0006_CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    C0006_UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    C0006_CREATED_BY UUID NOT NULL,
    C0006_UPDATED_BY UUID NOT NULL,
    C0006_SQ_ID INT NOT NULL DEFAULT nextval('seq_tb0006_team'),
    CONSTRAINT chk_team_name_length CHECK (LENGTH(TRIM(C0006_NAME)) >= 2),
    CONSTRAINT fk_team_company FOREIGN KEY (C0006_COMPANY_ID)
        REFERENCES TB0005_COMPANY(C0005_COMPANY_ID) ON DELETE CASCADE,
    CONSTRAINT fk_team_created_by FOREIGN KEY (C0006_CREATED_BY)
        REFERENCES TB0002_USER_AUTH(C0002_USER_ID),
    CONSTRAINT fk_team_updated_by FOREIGN KEY (C0006_UPDATED_BY)
        REFERENCES TB0002_USER_AUTH(C0002_USER_ID)
);

-- Criar Índices
CREATE UNIQUE INDEX IX0006_SQ_ID ON TB0006_TEAM (C0006_SQ_ID);
CREATE INDEX IX0006_COMPANY_ID ON TB0006_TEAM (C0006_COMPANY_ID);
CREATE INDEX IX0006_NAME ON TB0006_TEAM (C0006_NAME);
CREATE INDEX IX0006_ACTIVE ON TB0006_TEAM (C0006_ACTIVE) WHERE C0006_ACTIVE = TRUE;
CREATE INDEX IX0006_CREATED_BY ON TB0006_TEAM (C0006_CREATED_BY);
CREATE INDEX IX0006_CREATED_AT ON TB0006_TEAM (C0006_CREATED_AT DESC);
CREATE INDEX IX0006_COMPANY_NAME ON TB0006_TEAM (C0006_COMPANY_ID, C0006_NAME);

-- Adicionar Comentários
COMMENT ON TABLE TB0006_TEAM IS 'Tabela de times/equipes dentro de empresas';
COMMENT ON COLUMN TB0006_TEAM.C0006_TEAM_ID IS 'Identificador único do time';
COMMENT ON COLUMN TB0006_TEAM.C0006_COMPANY_ID IS 'ID da empresa à qual o time pertence';
COMMENT ON COLUMN TB0006_TEAM.C0006_NAME IS 'Nome do time';
COMMENT ON COLUMN TB0006_TEAM.C0006_DESCRIPTION IS 'Descrição do time';
COMMENT ON COLUMN TB0006_TEAM.C0006_ACTIVE IS 'Indica se o time está ativo';
COMMENT ON COLUMN TB0006_TEAM.C0006_CREATED_AT IS 'Data e hora de criação do registro';
COMMENT ON COLUMN TB0006_TEAM.C0006_UPDATED_AT IS 'Data e hora da última atualização do registro';
COMMENT ON COLUMN TB0006_TEAM.C0006_CREATED_BY IS 'ID do usuário que criou o registro';
COMMENT ON COLUMN TB0006_TEAM.C0006_UPDATED_BY IS 'ID do usuário que atualizou o registro pela última vez';
COMMENT ON COLUMN TB0006_TEAM.C0006_SQ_ID IS 'ID sequencial numérico';

-- Conceder Permissões
GRANT SELECT, INSERT, UPDATE, DELETE ON TB0006_TEAM TO "TIME-TRACKER-API";
GRANT USAGE, SELECT ON SEQUENCE seq_tb0006_team TO "TIME-TRACKER-API";
