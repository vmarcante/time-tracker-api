CREATE SEQUENCE seq_TB0001_PERSON START 1;

CREATE TABLE TB0001_PERSON (
    C0001_ID UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    C0001_NAME VARCHAR(100) NOT NULL,
    C0001_EMAIL VARCHAR(255) NOT NULL,
    C0001_PHONE VARCHAR(20),
    C0001_CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    C0001_UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    C0001_SQ_ID INT NOT NULL DEFAULT nextval('seq_TB0001_PERSON'),
    C0001_ACTIVE BOOLEAN DEFAULT TRUE NOT NULL,
    CONSTRAINT chk_name_length CHECK (LENGTH(TRIM(C0001_NAME)) >= 3),
    CONSTRAINT chk_email_length CHECK (LENGTH(TRIM(C0001_EMAIL)) >= 5)
);

CREATE UNIQUE INDEX IX0001_SQ_ID ON TB0001_PERSON (C0001_SQ_ID);
CREATE INDEX IX0001_ACTIVE ON TB0001_PERSON (C0001_ACTIVE) WHERE C0001_ACTIVE = TRUE;
CREATE UNIQUE INDEX IX0001_EMAIL_LOWER ON TB0001_PERSON (LOWER(C0001_EMAIL));
CREATE INDEX IX0001_CREATED_AT ON TB0001_PERSON (C0001_CREATED_AT DESC);

COMMENT ON TABLE TB0001_PERSON IS 'Tabela de dados pessoais da pessoa';
COMMENT ON COLUMN TB0001_PERSON.C0001_ID IS 'Identificador único da pessoa, compartilhado com TB0002_USER_AUTH se existir';
COMMENT ON COLUMN TB0001_PERSON.C0001_NAME IS 'Nome completo da pessoa';
COMMENT ON COLUMN TB0001_PERSON.C0001_EMAIL IS 'Endereço de email da pessoa';
COMMENT ON COLUMN TB0001_PERSON.C0001_PHONE IS 'Telefone da pessoa (formato brasileiro)';
COMMENT ON COLUMN TB0001_PERSON.C0001_SQ_ID IS 'ID sequencial numérico';
COMMENT ON COLUMN TB0001_PERSON.C0001_ACTIVE IS 'Indica se os dados da pessoa estão ativos';
